/** 按归一化框裁出图片。 */
internal fun Bitmap.cropTo(n: CropNorm): Bitmap {
    val x = (n.left * width).toInt().coerceIn(0, width - 1)
    val y = (n.top * height).toInt().coerceIn(0, height - 1)
    val w = ((n.right - n.left) * width).toInt().coerceIn(1, width - x)
    val h = ((n.bottom - n.top) * height).toInt().coerceIn(1, height - y)
    return Bitmap.createBitmap(this, x, y, w, h)
}

internal fun Bitmap.rotatedBy(degrees: Float): Bitmap {
    val matrix = Matrix().apply { postRotate(degrees) }
    return Bitmap.createBitmap(this, 0, 0, width, height, matrix, true)
}

internal fun Bitmap.mirrored(): Bitmap {
    val matrix = Matrix().apply { preScale(-1f, 1f) }
    return Bitmap.createBitmap(this, 0, 0, width, height, matrix, true)
}
